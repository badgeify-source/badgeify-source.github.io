-- Central directory of payment email addresses.
-- Safe to run after the earlier optional payment_email migration, or by itself.
ALTER TABLE public.subscriptions
ADD COLUMN IF NOT EXISTS payment_email text;

CREATE TABLE IF NOT EXISTS public.payment_emails (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS payment_emails_email_lower_uidx
ON public.payment_emails (lower(email));

ALTER TABLE public.subscriptions
ADD COLUMN IF NOT EXISTS payment_email_id bigint;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'subscriptions_payment_email_id_fkey'
          AND conrelid = 'public.subscriptions'::regclass
    ) THEN
        ALTER TABLE public.subscriptions
        ADD CONSTRAINT subscriptions_payment_email_id_fkey
        FOREIGN KEY (payment_email_id)
        REFERENCES public.payment_emails(id)
        ON DELETE RESTRICT;
    END IF;
END $$;

-- Import addresses already saved on subscriptions without changing old records.
INSERT INTO public.payment_emails (email)
SELECT DISTINCT lower(trim(payment_email))
FROM public.subscriptions
WHERE payment_email IS NOT NULL
  AND trim(payment_email) <> ''
ON CONFLICT DO NOTHING;

-- Link subscriptions to the matching saved email.
UPDATE public.subscriptions s
SET payment_email_id = e.id
FROM public.payment_emails e
WHERE s.payment_email_id IS NULL
  AND s.payment_email IS NOT NULL
  AND lower(trim(s.payment_email)) = lower(e.email);

ALTER TABLE public.payment_emails ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated users can manage payment emails" ON public.payment_emails;
CREATE POLICY "Authenticated users can manage payment emails"
ON public.payment_emails
FOR ALL
TO authenticated
USING (true)
WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.payment_emails TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.payment_emails_id_seq TO authenticated;
